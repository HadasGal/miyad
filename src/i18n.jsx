function readLang() {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v && LANGS[v]) return v;
  } catch (e) {
    // אחסון חסום: עברית
  }
  return 'he';
}

function format(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
}

const LangContext = createContext({ lang: 'he', setLang: () => {} });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(readLang);

  // כיוון, שפה וכותרת של המסמך כולו עוברים עם השפה
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = LANGS[lang].dir;
    document.title = STRINGS[lang]['app.title'];
  }, [lang]);

  const setLang = (l) => {
    try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* בלי שמירה, רק לסשן */ }
    setLangState(l);
  };

  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

// L: תוכן { he, en } לפי שפה. מחרוזת רגילה (תוכן של משתמשת) חוזרת כמו שהיא.
export const pick = (v, lang) => (v && typeof v === 'object' ? (v[lang] ?? v.he) : (v ?? ''));

export function useT() {
  const { lang, setLang } = useContext(LangContext);
  const dict = STRINGS[lang];
  // {n} === 1 בוחר את המפתח עם .one אם יש, לרבים באנגלית
  const t = (key, vars) => {
    const one = vars?.n === 1 ? dict[`${key}.one`] : undefined;
    return format(one ?? dict[key] ?? STRINGS.he[key] ?? key, vars);
  };
  const L = (v) => pick(v, lang);
  const ago = (ts) => {
    const m = Math.floor(Math.max(0, Date.now() - ts) / 60000);
    if (m < 1) return t('ago.now');
    if (m < 60) return m === 1 ? t('ago.minute') : t('ago.minutes', { n: m });
    const h = Math.floor(m / 60);
    if (h < 24) return h === 1 ? t('ago.hour') : h === 2 ? t('ago.twoHours') : t('ago.hours', { n: h });
    const d = Math.floor(h / 24);
    return d === 1 ? t('ago.yesterday') : d === 2 ? t('ago.twoDays') : t('ago.days', { n: d });
  };
  return { lang, setLang, dir: LANGS[lang].dir, t, L, ago };
}
